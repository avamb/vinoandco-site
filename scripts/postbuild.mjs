// After `astro build`: hash every inline <script> and <style> Astro left in the
// HTML (island runtime, island styles) and write them as nginx variables, so the
// Content Security Policy can stay strict ('self' + hashes, no 'unsafe-inline').
// Output: dist/.nginx/csp-hashes.conf (and redirects.conf from redirects.yaml),
// included by nginx/default.conf.template. See spec 62 §3.1.
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { writeNginxRedirects } from './gen-nginx-redirects.mjs';

const toPath = (u) => decodeURIComponent(new URL(u, import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1');
const root = toPath('../');
const dist = toPath('../dist/');

function* htmlFiles(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* htmlFiles(p);
    else if (name.endsWith('.html')) yield p;
  }
}

const hash = (s) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`;
const scripts = new Set();
const styles = new Set();
let pages = 0;
for (const file of htmlFiles(dist)) {
  pages++;
  const html = readFileSync(file, 'utf8');
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)) {
    if (m[1].trim()) scripts.add(hash(m[1]));
  }
  for (const m of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)) {
    if (m[1].trim()) styles.add(hash(m[1]));
  }
  if (/\sstyle="/i.test(html)) {
    console.warn(`postbuild: inline style attribute in ${file} (blocked by CSP)`);
  }
}

mkdirSync(join(dist, '.nginx'), { recursive: true });
writeFileSync(
  join(dist, '.nginx', 'csp-hashes.conf'),
  `# Generated by scripts/postbuild.mjs — do not edit.\nset $csp_script_hashes "${[...scripts].join(' ')}";\nset $csp_style_hashes "${[...styles].join(' ')}";\n`,
);
writeNginxRedirects(root, dist);
console.log(`postbuild: ${pages} pages, ${scripts.size} inline script hash(es), ${styles.size} inline style hash(es)`);
